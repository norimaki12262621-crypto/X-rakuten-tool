const MACRO_KEYS = Object.keys(MACRO_COPY);

function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

// ギフトサブタイプ判定（inferMacroCategory がギフト文脈を検出した後に呼ぶ）
function inferGiftSubtype(s) {
  if (/高級|贅沢|プレミアム|premium|luxury|シャンパン|スパークリングワイン|ワイン|ウイスキー|ブランデー|日本酒[^\s]*本醸造|和牛|松阪|神戸牛|近江牛|黒毛和牛|メロン|マンゴー|白桃|さくらんぼ|サクランボ|ずわいがに|ズワイガニ|毛蟹|毛ガニ|伊勢海老|タラバガニ|タラバ/.test(s)) return 'gift_luxury';
  if (/面白い|おもしろ|ユニーク|ネタ|珍しい|変わった|個性的|ユーモア|笑え|サプライズ/.test(s)) return 'gift_fun';
  if (/名入れ|名前入り|刻印|オーダーメイド|カスタム|フラワー|花束|アレンジメント|ありがとう|感謝|メッセージカード/.test(s)) return 'gift_emotional';
  if (/タオル|バスタオル|石鹸|せっけん|洗剤|ハンドクリーム|入浴剤|バスソルト|コーヒー|珈琲|お茶|緑茶|紅茶|調味料|醤油|日用品|消耗品/.test(s)) return 'gift_practical';
  return 'gift_safe';
}

// テキストから大カテゴリを推定（優先度順）
function inferMacroCategory(text) {
  const s = (text || '').toLowerCase();
  if (/傘|レインコート|防水|雨具|雨対策|梅雨|除湿|湿気|部屋干し/.test(s)) return 'rainy';
  if (/犬|いぬ|ドッグ|猫|ねこ|キャット|ペット|フード|おやつ|餌|ペット用/.test(s)) return 'pet';
  if (/イヤホン|ヘッドフォン|ヘッドホン|ワイヤレス|モバイルバッテリー|充電器|充電ケーブル|急速充電|小型家電|加湿器|扇風機|掃除機/.test(s)) return 'gadget';
  if (/ギフト|プレゼント|贈り物|母の日|父の日|誕生日|クリスマス|結婚祝い|出産祝い|卒業|入学|就職|記念日|お年賀|バレンタイン|ホワイトデー|敬老|昇進/.test(s)) return inferGiftSubtype(s);
  if (/美容|コスメ|化粧|スキンケア|保湿|日焼け止め|uv|美容液|乳液|化粧水|クリーム|ヘアケア|ヘア|髪|シャンプー|トリートメント|ヘアオイル|ドライヤー|ネイル|メイク/.test(s)) return 'beauty';
  if (/食品|食材|お取り寄せ|グルメ|惣菜|肉|魚|米|スイーツ|お菓子|チョコ|ラーメン|麺|海鮮|だし|出汁|冷凍|料理|ごはん|コーヒー|珈琲|お茶|飲料/.test(s)) return 'food';
  if (/子ども|子供|キッズ|ベビー|赤ちゃん|入園|おもちゃ|知育|ランドセル|保育|幼稚|育児/.test(s)) return 'kids';
  if (/服|バッグ|財布|帽子|ワンピ|トップス|パンツ|コーデ|ファッション|アクセ|スニーカー|ブーツ|コート|ジャケット/.test(s)) return 'fashion';
  if (/収納|掃除|洗濯|キッチン|調理|台所|食器|鍋|フライパン|インテリア|寝具|枕|布団|照明|ラグ|カーテン|便利グッズ|生活雑貨/.test(s)) return 'home';
  return 'other';
}

function normalizeMacroCategory(cat) {
  return MACRO_KEYS.includes(cat) ? cat : 'other';
}

function selectCopy(text) {
  return MACRO_COPY[inferMacroCategory(text)];
}

// 感情描写（情景・空気感・体験）を返す
function selectScene(text) {
  return pick(selectCopy(text).scenes);
}

function buildPost(price, text) {
  const copy = selectCopy(text);
  const hook  = pick(copy.hooks);
  const scene = pick(copy.scenes);
  const echo  = pick(copy.echoes);
  const priceStr = `¥${Number(price).toLocaleString()}`;
  return `${hook}\n\n${scene}\n\n${priceStr}／${echo}`;
}

